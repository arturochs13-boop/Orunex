"""Deterministic Programmer-mode scaffolds.

This module keeps the VS Code integration useful even when the local LLM is
unavailable.  It does not pretend to be a full code model: it creates a clean,
runnable starter project, a test file and a README, then the desktop app opens
it in VS Code and runs the tests in the integrated terminal.  When the brain is
back, the same bridge can be used to apply AI-generated edits.
"""

