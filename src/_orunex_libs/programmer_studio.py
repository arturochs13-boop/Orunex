def scaffold(task: str, root: Optional[str] = None) -> dict:
    """Create a small runnable project and return its metadata."""
    task = _clean_task(task)
    language = detect_language(task)
    title = task[:80] or "Orunex Project"
    # Strip command noise from the title used in README/UI.
    title = re.sub(r"(?i)^(crea|crear|programa|programar|haz|hazme|genera|generar|build|create|make)\s+", "", title).strip()
    title = title[:1].upper() + title[1:] if title else "Orunex Project"
    slug = _safe_slug(task)
    folder = os.path.abspath(os.path.join(root or DEFAULT_ROOT, slug))
    os.makedirs(folder, exist_ok=True)

    if language == "web":
        files, entry, test_command = _web_project(task, title)
    elif language == "javascript":
        files, entry, test_command = _javascript_project(task, title)
    elif language == "python-flask":
        files, entry, test_command = _python_project(task, title)
    else:
        files, entry, test_command = _python_project(task, title)

    for name, content in files.items():
        path = os.path.join(folder, name)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)

    return {
        "ok": True,
        "folder": folder,
        "title": title,
        "language": language,
        "entry": os.path.join(folder, entry),
        "files": [os.path.join(folder, name) for name in files],
        "testCommand": test_command,
        "readme": os.path.join(folder, "README.md"),
    }
