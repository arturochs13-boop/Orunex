def _safe_slug(value: str) -> str:
    text = value.lower()
    text = (
        text.replace("á", "a").replace("é", "e").replace("í", "i")
        .replace("ó", "o").replace("ú", "u").replace("ñ", "n")
    )
    text = re.sub(r"[^a-z0-9]+", "_", text).strip("_")
    return (text or "orunex_project")[:48]


def _clean_task(value: str) -> str:
    return re.sub(r"\s+", " ", str(value or "")).strip()


def detect_language(task: str) -> str:
    lower = _clean_task(task).lower()
    if any(word in lower for word in ("html", "landing", "pagina web", "página web", "web page", "css", "frontend")):
        return "web"
    if any(word in lower for word in ("javascript", "typescript", "node", "express", "react")):
        return "javascript"
    if any(word in lower for word in ("flask", "fastapi", "api rest", "endpoint")):
        return "python-flask"
    return "python"


